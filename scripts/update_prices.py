OUT=ROOT/"js"/"live-data.js"
DAM_URL="https://market.dam.gov.bd/market_daily_price_report/damweb/PublicPortal/damweb/PublicPortal/index.php?L=B"
BRTA_URL="https://brta.gov.bd/pages/static-pages/6922de1b933eb65569e184a9"

