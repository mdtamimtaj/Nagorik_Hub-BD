def fetch(url:str)->str:
    req=Request(url,headers={"User-Agent":"NagorikHub-DailyUpdater/1.0"})
    with urlopen(req,timeout=30) as r:
        return r.read().decode("utf-8","ignore")

def norm(s:str)->str:
    s=html.unescape(s).lower()
    s=re.sub(r"\s+"," ",s)
    return re.sub(r"[^\w\u0980-\u09ff(). -]","",s).strip()

def parse_range(text:str):
    m=re.search(r"([0-9]+(?:\.[0-9]+)?)\s*[-–]\s*([0-9]+(?:\.[0-9]+)?)",text)
    if not m: return None
    return float(m.group(1)),float(m.group(2))

def dam_prices(page:str, today:str):
    # Strip tags to a stable text representation.
    txt=re.sub(r"<[^>]+>"," ",page)
    txt=re.sub(r"\s+"," ",html.unescape(txt))
    result={}
    for site_name,(dam_name,unit) in DAM_MAP.items():
        pos=txt.lower().find(dam_name.lower())
        if pos<0:
            continue
        part=txt[pos:pos+180]
        rg=parse_range(part)
        if rg:
            lo,hi=rg
            result[site_name]={"min":lo,"max":hi,"unit":unit,"source":"DAM","updated":today}
    return result

def load_static():
    # Keep the site's known route table as the safe verified baseline.
    p=ROOT/"js"/"official-data.js"
    s=p.read_text(encoding="utf-8")
    # Extract the routes array from the JS with a simple bracket match.
    marker="routes:"
    i=s.find(marker)
    if i<0: return []
    start=s.find("[",i); end=s.find("]",start)
    raw=s[start:end+1]
    raw=raw.replace("from:","\"from\":").replace("to:","\"to\":").replace("nonAc40:","\"nonAc40\":").replace("nonAc51:","\"nonAc51\":")
    try:
        return json.loads(raw)
    except Exception:
        return []

def main():
    now=datetime.now(timezone.utc)
    today=now.date().isoformat()
    live={"updatedAt":now.isoformat(),"market":{},"retail":{},"bus":{"routes":load_static(),"updated":"2026-04-23","source":"BRTA","sourceUrl":BRTA_URL}}

    # DAM is the authoritative first source. If it fails, keep the last known
    # static values instead of publishing an empty/incorrect update.
    try:
        page=fetch(DAM_URL)
        live["market"]=dam_prices(page,today)
    except Exception as exc:
        print("DAM fetch failed:",exc)

    # Backup source is intentionally represented as a separate adapter.
    # Add a verified retailer adapter here when its public markup/API is stable.
    # The site never labels fallback values as DAM.
    live["retail"]={}

    OUT.write_text(
        "// Auto-generated by daily-update.yml\nwindow.NAGORIK_LIVE="+
        json.dumps(live,ensure_ascii=False,indent=2)+";\n",
        encoding="utf-8"
    )
    print("Updated",OUT)

if __name__=="__main__":
    main()
