#!/usr/bin/env python3
"""
Nagorik Hub daily updater.

Priority:
1) DAM official daily market report
2) Backup retail source adapters (only for products missing in DAM)
3) BRTA official source metadata + maintained verified route table

The script writes js/live-data.js. GitHub Actions runs it once every day.
"""
